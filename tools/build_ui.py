#!/usr/bin/env python3
"""Embed firmware/ui/index.html into firmware/ripeomatic/ui.h as a PROGMEM string.

Run after editing the HTML:  python3 tools/build_ui.py
The generated header is committed so Arduino IDE users don't need this step.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "firmware" / "ui" / "index.html"
dst = root / "firmware" / "ripeomatic" / "ui.h"

html = src.read_text(encoding="utf-8")
# light minify: drop blank lines and leading indentation (keeps the JS readable in a debugger)
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
delim = "RIPEUI"
assert f"){delim}\"" not in html, "raw-string delimiter collides with the HTML"

manifest = (
    '{"name":"Ripe-O-Matic","short_name":"Ripe-O-Matic","start_url":"/","display":"standalone",'
    '"background_color":"#f4f3ec","theme_color":"#2e4a21",'
    '"icons":[{"src":"/icon.svg","sizes":"any","type":"image/svg+xml","purpose":"any"}]}'
)
icon = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
    '<rect width="64" height="64" rx="14" fill="#2e4a21"/>'
    '<path d="M32 6c8 0 12 9 13 18 2 12 8 17 8 24 0 6-9 9-21 9S11 54 11 48c0-7 6-12 8-24C20 15 24 6 32 6z" fill="#8bc65d"/>'
    '<path d="M32 13c5 0 8 7 9 15 1 9 6 14 6 19 0 4-7 6-15 6s-15-2-15-6c0-5 5-10 6-19 1-8 4-15 9-15z" fill="#e3f0c3"/>'
    '<circle cx="32" cy="45" r="7" fill="#6b4a2b"/></svg>'
)
sw = (
    "self.addEventListener('install',e=>self.skipWaiting());"
    "self.addEventListener('activate',e=>self.clients.claim());"
    "self.addEventListener('fetch',e=>{});"
)

out = f"""// GENERATED by tools/build_ui.py from firmware/ui/index.html. Do not edit by hand.
#pragma once
#include <Arduino.h>

static const char UI_HTML[] PROGMEM = R"{delim}({html}){delim}";

static const char UI_MANIFEST[] PROGMEM = R"{delim}({manifest}){delim}";

static const char UI_ICON_SVG[] PROGMEM = R"{delim}({icon}){delim}";

static const char UI_SW_JS[] PROGMEM = R"{delim}({sw}){delim}";
"""
dst.write_text(out, encoding="utf-8")
print(f"wrote {dst.relative_to(root)}: html {len(html)} bytes")
